#!/usr/bin/env python3
"""Zero-dependency structural analyzers and vendor filters for non-Python files.

Provides lightweight, standard-library-only structural scanning for:
- C-style brace languages (.js, .ts, .tsx, .jsx, .dart, .go, .rs, .cs)
- Stylesheets (.css, .scss, .less)
- Unknown/fallback source files (keyword + block span heuristics)
- Vendor, minified, and machine-emitted asset detection
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

BRACE_EXTENSIONS: frozenset[str] = frozenset({
    ".js", ".ts", ".tsx", ".jsx", ".dart", ".go", ".rs", ".cs",
    ".java", ".kt", ".swift", ".c", ".cpp", ".h", ".hpp", ".php",
})

STYLE_EXTENSIONS: frozenset[str] = frozenset({".css", ".scss", ".less"})

VENDOR_DIR_NAMES: frozenset[str] = frozenset({
    "vendor", "vendors", "third_party", "third-party", "extern",
    "external", "bower_components", "libs", "bootstrap", "fontawesome",
})

VENDOR_FILE_PREFIXES: tuple[str, ...] = (
    "jquery", "slick.", "bootstrap", "tailwind", "lodash", "moment.",
    "fontawesome", "font-awesome", "linearicons", "ionicons", "normalize.",
    "animate.", "prism.", "select2", "datatables", "popper.", "axios.",
    "htmx.", "alpine.", "chart.js", "three.", "d3.", "swiper.",
    "magnific-popup", "nice-select", "owl.carousel", "superfish",
)

GENERATED_SUFFIXES: tuple[str, ...] = (
    ".min.js", ".min.css", "-min.js", "-min.css", ".bundle.js",
    ".bundle.css", ".g.dart", ".freezed.dart", ".pb.go", ".generated.ts",
    ".generated.cs", ".designer.cs",
)

GENERATED_MARKERS: tuple[str, ...] = (
    "@generated", "do not edit", "autogenerated by", "generated code - do not",
    "sourcemappingurl=",
)


@dataclass
class RawSymbol:
    """Lightweight intermediate representation of a parsed class or function."""

    kind: str  # "class" or "func"
    name: str
    qualname: str
    start_line: int
    end_line: int
    lines: int
    methods: list[str] = field(default_factory=list)


_CLASS_RE = re.compile(
    r"^\s*(?:export\s+)?(?:default\s+)?(?:public\s+|private\s+|internal\s+|abstract\s+|sealed\s+|partial\s+)*"
    r"(?:class|struct|interface|impl|mixin|extension)\s+(?:<[^>]+>\s*)?([A-Za-z_]\w*)"
)
_GO_STRUCT_RE = re.compile(r"^\s*type\s+([A-Za-z_]\w*)\s+(?:struct|interface)\b")
_GO_METHOD_RE = re.compile(
    r"^\s*func\s+\(\s*\w+\s+\*?([A-Za-z_]\w*)\s*\)\s*([A-Za-z_]\w*)\s*\("
)
_FUNC_RE = re.compile(
    r"^\s*(?:export\s+)?(?:default\s+)?(?:public\s+|private\s+|protected\s+|internal\s+|static\s+|async\s+|inline\s+|pub(?:\([^)]+\))?\s+)*"
    r"(?:func|fn|function|def)\s+([A-Za-z_]\w*)\s*[<(]"
)
_ARROW_FUNC_RE = re.compile(
    r"^\s*(?:export\s+)?(?:const|let|var)\s+([A-Za-z_]\w*)\s*(?::[^=]+)?=\s*(?:async\s*)?(?:\([^)]*\)|[A-Za-z_]\w*)\s*(?::[^=]+)?=>"
)
_TYPED_METHOD_RE = re.compile(
    r"^\s*(?:public\s+|private\s+|protected\s+|internal\s+|static\s+|virtual\s+|override\s+|async\s+|Future(?:<[^>]+>)?\s+|void\s+)+"
    r"(?:[A-Za-z_][\w<>?,\[\]\s]*\s+)?([A-Za-z_]\w*)\s*\("
)
_CLASS_METHOD_RE = re.compile(
    r"^\s*(?:public\s+|private\s+|protected\s+|static\s+|async\s+|get\s+|set\s+|override\s+)*"
    r"(?:[A-Za-z_][\w<>?,\[\]\s]*\s+)?([A-Za-z_]\w*)\s*\("
)
_CONTROL_KEYWORDS: frozenset[str] = frozenset({
    "if", "for", "while", "switch", "catch", "return", "sizeof", "typeof",
    "match", "super", "new", "import", "require", "else", "try",
})


def is_vendor_or_generated(
    file_path: Path,
    rel_parts: tuple[str, ...] = (),
    sample_lines: list[str] | None = None,
) -> bool:
    """Return True if path or header indicates a third-party vendor or generated file."""
    lower_name = file_path.name.lower()
    if any(lower_name.endswith(sfx) for sfx in GENERATED_SUFFIXES):
        return True
    if any(lower_name.startswith(pfx) for pfx in VENDOR_FILE_PREFIXES):
        return True
    check_parts = {p.lower() for p in (rel_parts[:-1] if rel_parts else file_path.parts[-3:-1])}
    if check_parts & VENDOR_DIR_NAMES:
        return True
    if sample_lines:
        header = "\n".join(sample_lines[:8]).lower()
        if any(marker in header for marker in GENERATED_MARKERS):
            return True
        if any(len(line) > 500 for line in sample_lines[:5]):
            return True
    return False


def _strip_block_comments(source_text: str) -> str:
    """Replace multi-line /* ... */ comments with blank lines to preserve line numbers."""
    return re.sub(
        r"/\*.*?\*/",
        lambda m: "\n" * m.group(0).count("\n"),
        source_text,
        flags=re.DOTALL,
    )


def _strip_strings_and_comments(line: str) -> str:
    """Remove string literals and single-line comments to count braces safely."""
    cleaned = re.sub(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|`(?:\\.|[^`\\])*`', '""', line)
    return re.sub(r"//.*$", "", cleaned)


def _has_opening_brace(lines: list[str], start_idx: int) -> bool:
    """Check if a declaration opens a `{` block within 6 lines without ending in `;`."""
    limit = min(len(lines), start_idx + 6)
    for idx in range(start_idx, limit):
        cleaned = _strip_strings_and_comments(lines[idx]).strip()
        if "{" in cleaned:
            return True
        if cleaned.endswith(";"):
            return False
    return False


def _find_block_end(lines: list[str], start_idx: int) -> int:
    """Track curly brace depth from start_idx (0-based) and return 1-based end line."""
    depth = 0
    found_open = False
    for idx in range(start_idx, len(lines)):
        cleaned = _strip_strings_and_comments(lines[idx])
        opens = cleaned.count("{")
        closes = cleaned.count("}")
        if opens > 0:
            found_open = True
        depth += opens - closes
        if found_open and depth <= 0:
            return idx + 1
        if not found_open and idx > start_idx + 6:
            return start_idx + 1
    return len(lines)


def _match_brace_symbol(
    line: str, in_class: bool
) -> tuple[str, str, str | None] | None:
    """Identify ('class'|'func', name, receiver_or_none) on a source line."""
    cleaned = _strip_strings_and_comments(line)
    for pat in (_CLASS_RE, _GO_STRUCT_RE):
        m = pat.match(cleaned)
        if m:
            return ("class", m.group(1), None)
    m_go = _GO_METHOD_RE.match(cleaned)
    if m_go:
        return ("func", m_go.group(2), m_go.group(1))
    for pat in (_FUNC_RE, _ARROW_FUNC_RE, _TYPED_METHOD_RE):
        m = pat.match(cleaned)
        if m and m.group(1) not in _CONTROL_KEYWORDS:
            return ("func", m.group(1), None)
    if in_class and "=" not in cleaned.split("(")[0]:
        m_cls = _CLASS_METHOD_RE.match(cleaned)
        if m_cls and m_cls.group(1) not in _CONTROL_KEYWORDS:
            return ("func", m_cls.group(1), None)
    return None


def _record_brace_symbol(
    kind: str,
    name: str,
    recv: str | None,
    lineno: int,
    end_line: int,
    classes: dict[str, RawSymbol],
    funcs: list[RawSymbol],
    active_class: RawSymbol | None,
) -> tuple[RawSymbol | None, int]:
    """Store a parsed class or function symbol and return updated (active_class, func_end)."""
    span = max(1, end_line - lineno + 1)
    if kind == "class":
        sym = classes.get(name) or RawSymbol("class", name, name, lineno, end_line, span, [])
        sym.end_line = max(sym.end_line, end_line)
        sym.lines = max(sym.lines, span)
        classes[name] = sym
        return sym, 0
    owner = recv or (active_class.name if active_class else None)
    if owner and name != "constructor":
        parent = classes.setdefault(
            owner, RawSymbol("class", owner, owner, lineno, end_line, span, [])
        )
        parent.methods.append(name)
    qual = f"{owner}.{name}" if owner else name
    funcs.append(RawSymbol("func", name, qual, lineno, end_line, span))
    return active_class, end_line


def analyze_brace_language(source_text: str) -> list[RawSymbol]:
    """Extract classes/structs/impls and functions/methods from C-style brace files."""
    # remove multi-line comment blocks so they don't corrupt the block depth counter.
    lines = _strip_block_comments(source_text).splitlines()
    classes: dict[str, RawSymbol] = {}
    funcs: list[RawSymbol] = []
    active_class: RawSymbol | None = None
    active_func_end: int = 0

    for idx, line in enumerate(lines):
        lineno = idx + 1
        if active_class and lineno > active_class.end_line:
            active_class = None
        matched = _match_brace_symbol(line, in_class=bool(active_class and lineno > active_func_end))
        if not matched or not _has_opening_brace(lines, idx):
            continue
        end_line = _find_block_end(lines, idx)
        active_class, fn_end = _record_brace_symbol(
            matched[0], matched[1], matched[2], lineno, end_line, classes, funcs, active_class
        )
        active_func_end = max(active_func_end, fn_end)

    return list(classes.values()) + funcs


_CSS_SECTION_RE = re.compile(r"/\*\s*[=*#-]{2,}\s*([^*]+?)\s*[=*#-]{2,}\s*\*/")
_CSS_RULE_RE = re.compile(r"^\s*([.#@:][^{;]+?)\s*\{")


def analyze_stylesheet(source_text: str) -> list[RawSymbol]:
    """Extract section groups, @media/@layer blocks, and large rule spans from CSS/SCSS."""
    lines = source_text.splitlines()
    symbols: list[RawSymbol] = []
    prefix_groups: dict[str, list[str]] = {}
    prefix_bounds: dict[str, tuple[int, int]] = {}

    for idx, line in enumerate(lines):
        lineno = idx + 1
        m_sec = _CSS_SECTION_RE.search(line)
        if m_sec:
            sec_name = f"Section:{m_sec.group(1).strip()[:28]}"
            symbols.append(RawSymbol("class", sec_name, sec_name, lineno, lineno, 1, []))
            continue
        m_rule = _CSS_RULE_RE.match(line)
        if not m_rule:
            continue
        selector = m_rule.group(1).strip()
        end_line = _find_block_end(lines, idx)
        span = max(1, end_line - lineno + 1)
        if span >= 25 or selector.startswith(("@media", "@keyframes", ":root")):
            symbols.append(RawSymbol("func", selector[:36], selector[:36], lineno, end_line, span))
        prefix = re.split(r"[\s>+~:#.\[]", selector.lstrip(".#"))[0]
        if prefix and not selector.startswith("@"):
            key = f".{prefix}*"
            prefix_groups.setdefault(key, []).append(selector[:24])
            start_b, _ = prefix_bounds.get(key, (lineno, end_line))
            prefix_bounds[key] = (start_b, end_line)

    for pfx, rules in prefix_groups.items():
        if len(rules) >= 6:
            s_line, e_line = prefix_bounds[pfx]
            symbols.append(RawSymbol("class", pfx, pfx, s_line, e_line, e_line - s_line + 1, rules))
    return symbols


_FALLBACK_DECL_RE = re.compile(
    r"^\s*(?:public\s+|private\s+|export\s+|async\s+)*"
    r"(?:def|fn|func|function|class|module|sub|proc)\s+([A-Za-z_]\w*)"
)


def analyze_generic_fallback(source_text: str) -> list[RawSymbol]:
    """Heuristic keyword line-span scanner for unknown or unsupported languages."""
    lines = source_text.splitlines()
    decls = [
        (idx + 1, m.group(1))
        for idx, line in enumerate(lines)
        if (m := _FALLBACK_DECL_RE.match(line))
    ]
    symbols: list[RawSymbol] = []
    for i, (start_line, name) in enumerate(decls):
        end_line = (decls[i + 1][0] - 1) if i + 1 < len(decls) else len(lines)
        symbols.append(RawSymbol("func", name, name, start_line, end_line, max(1, end_line - start_line + 1)))
    return symbols
